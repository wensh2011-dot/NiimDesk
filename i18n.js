function detect() {
  try {
    const saved = localStorage.getItem("ls.lang");
    if (saved && D[saved]) return saved;
    // users of the earlier Arabic-only version keep Arabic
    if (localStorage.getItem("ls.project")) return "ar";
  } catch {}
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const c = String(l).slice(0, 2).toLowerCase();
    if (D[c]) return c;
  }
  return "en";
}

export const LANG = detect();
export const LANG_INFO = LANGS.find((l) => l.code === LANG);

// t("key", {var: value}) → translated string with {var} placeholders filled in
export function t(key, vars) {
  let s = D[LANG][key] ?? D.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function setLang(code) {
  try { localStorage.setItem("ls.lang", code); } catch {}
  location.reload();
}

// fill static page text: data-i18n (text), data-i18n-html (markup), data-i18n-tip (tooltip)
export function applyStatic(root = document) {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG_INFO.dir;
  root.querySelectorAll("[data-i18n]").forEach((e) => (e.textContent = t(e.dataset.i18n)));
  root.querySelectorAll("[data-i18n-html]").forEach((e) => (e.innerHTML = t(e.dataset.i18nHtml)));
  root.querySelectorAll("[data-i18n-tip]").forEach((e) => (e.dataset.tip = t(e.dataset.i18nTip)));
}
